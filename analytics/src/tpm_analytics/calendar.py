"""German public-holiday and school-holiday calendar for the training set.

The dataset is generated by ``scripts/build_calendar.py`` and committed under
``tpm_analytics/data/calendar.json``. This module only reads the packaged file and expands it into
a small daily table that the training builder can join to route-days.

It deliberately does not call the network, read S3 or open a DuckDB connection at import time.
"""

from __future__ import annotations

import csv
import json
import tempfile
from bisect import bisect_left, bisect_right
from dataclasses import dataclass
from datetime import date, datetime, timedelta
from pathlib import Path
from typing import TYPE_CHECKING, Any
from zoneinfo import ZoneInfo

if TYPE_CHECKING:
    import duckdb

SCHEMA_VERSION = 1
BERLIN = ZoneInfo("Europe/Berlin")
SCHOOL_TYPES = frozenset({"summer", "christmas", "easter", "autumn", "winter", "whitsun", "other"})
PUBLIC_HOLIDAY_SCOPES = frozenset({"National", "Regional"})
STATE_CODES_BY_NAME = {
    "Baden-Württemberg": "BW",
    "Bayern": "BY",
    "Berlin": "BE",
    "Brandenburg": "BB",
    "Bremen": "HB",
    "Hamburg": "HH",
    "Hessen": "HE",
    "Mecklenburg-Vorpommern": "MV",
    "Niedersachsen": "NI",
    "Nordrhein-Westfalen": "NW",
    "Rheinland-Pfalz": "RP",
    "Saarland": "SL",
    "Sachsen": "SN",
    "Sachsen-Anhalt": "ST",
    "Schleswig-Holstein": "SH",
    "Thüringen": "TH",
}
STATE_CODES = tuple(STATE_CODES_BY_NAME.values())

DAILY_COLUMNS = (
    "state_code",
    "date",
    "is_public_holiday",
    "public_holiday_name",
    "public_holiday_scope",
    "days_to_next_public_holiday",
    "days_since_prev_public_holiday",
    "is_public_holiday_window",
    "is_school_holiday",
    "school_holiday_name",
    "school_holiday_type",
    "school_holiday_day",
    "days_until_school_holiday_end",
    "is_school_holiday_start_window",
    "is_school_holiday_end_window",
    "is_bridge_day",
)

_DAILY_TYPES = (
    "VARCHAR",
    "DATE",
    "BOOLEAN",
    "VARCHAR",
    "VARCHAR",
    "INTEGER",
    "INTEGER",
    "BOOLEAN",
    "BOOLEAN",
    "VARCHAR",
    "VARCHAR",
    "INTEGER",
    "INTEGER",
    "BOOLEAN",
    "BOOLEAN",
    "BOOLEAN",
)


class CalendarError(ValueError):
    """The calendar data or the requested range is invalid."""


class CalendarCoverageError(CalendarError):
    """A requested date falls outside the committed calendar coverage."""


@dataclass(frozen=True)
class PublicHoliday:
    state: str
    day: date
    name: str
    scope: str


@dataclass(frozen=True)
class SchoolHoliday:
    state: str
    start: date
    end: date
    name: str
    kind: str


@dataclass(frozen=True)
class Calendar:
    schema_version: int
    calendar_version: str
    coverage_start: date
    coverage_end: date
    states: dict[str, str]
    public_holidays: tuple[PublicHoliday, ...]
    school_holidays: tuple[SchoolHoliday, ...]


def _calendar_path() -> Path:
    """Return the packaged calendar file path."""
    return Path(__file__).resolve().parent / "data" / "calendar.json"


def _as_date(value: date | datetime | str) -> date:
    """Coerce a date or datetime to the Europe/Berlin calendar date."""
    if isinstance(value, datetime):
        if value.tzinfo is not None:
            return value.astimezone(BERLIN).date()
        return value.date()
    return value if isinstance(value, date) else date.fromisoformat(value)


def _normalize_state_name(name: str) -> str:
    """Collapse whitespace in a state name."""
    return " ".join(name.split())


def state_code(name: str) -> str:
    """Map a state name, a two-letter code or an ISO ``DE-XX`` code to ``XX``."""
    normalized = _normalize_state_name(name)
    if normalized in STATE_CODES:
        return normalized
    upper = normalized.upper()
    if upper.startswith("DE-") and upper[3:] in STATE_CODES:
        return upper[3:]
    try:
        return STATE_CODES_BY_NAME[normalized]
    except KeyError as error:
        raise CalendarError(f"unknown German state {name!r}") from error


def _parse_calendar(payload: dict[str, Any]) -> Calendar:
    """Validate a JSON payload and convert it to a Calendar."""
    try:
        schema_version = int(payload["schema_version"])
        calendar_version = str(payload["calendar_version"])
        coverage = payload["coverage"]
        coverage_start = date.fromisoformat(coverage["from"])
        coverage_end = date.fromisoformat(coverage["to"])
        raw_states = payload["states"]
        state_codes = [str(item["code"]) for item in raw_states]
        if len(state_codes) != len(set(state_codes)):
            raise ValueError("duplicate state codes")
        states = {str(item["code"]): str(item["name"]) for item in raw_states}
        public_holidays = tuple(
            PublicHoliday(
                state=str(item["state"]),
                day=date.fromisoformat(item["date"]),
                name=str(item["name"]),
                scope=str(item["scope"]),
            )
            for item in payload["public_holidays"]
        )
        school_holidays = tuple(
            SchoolHoliday(
                state=str(item["state"]),
                start=date.fromisoformat(item["start"]),
                end=date.fromisoformat(item["end"]),
                name=str(item["name"]),
                kind=str(item["type"]),
            )
            for item in payload["school_holidays"]
        )
    except (KeyError, TypeError, ValueError) as error:
        raise CalendarError(f"invalid calendar data: {error}") from error

    if schema_version != SCHEMA_VERSION:
        raise CalendarError(f"unsupported calendar schema {schema_version}; expected {SCHEMA_VERSION}")
    if not calendar_version.strip():
        raise CalendarError("calendar version is empty")
    if coverage_start > coverage_end:
        raise CalendarError("calendar coverage starts after it ends")
    if set(states) != set(STATE_CODES):
        raise CalendarError(f"calendar states do not match the 16 German states: {sorted(states)}")
    for code, name in states.items():
        if STATE_CODES_BY_NAME.get(name) != code:
            raise CalendarError(f"calendar state {code!r} has unexpected name {name!r}")
    public_keys = {(holiday.state, holiday.day, holiday.name, holiday.scope) for holiday in public_holidays}
    if len(public_keys) != len(public_holidays):
        raise CalendarError("calendar has duplicate public holidays")
    school_keys = {
        (holiday.state, holiday.start, holiday.end, holiday.name, holiday.kind) for holiday in school_holidays
    }
    if len(school_keys) != len(school_holidays):
        raise CalendarError("calendar has duplicate school holidays")
    for holiday in public_holidays:
        if holiday.state not in states:
            raise CalendarError(f"public holiday for unknown state {holiday.state!r}")
        if holiday.scope not in PUBLIC_HOLIDAY_SCOPES:
            raise CalendarError(f"public holiday has unknown scope {holiday.scope!r}")
        if not coverage_start <= holiday.day <= coverage_end:
            raise CalendarError(f"public holiday outside coverage: {holiday}")
    for holiday in school_holidays:
        if holiday.state not in states:
            raise CalendarError(f"school holiday for unknown state {holiday.state!r}")
        if holiday.kind not in SCHOOL_TYPES:
            raise CalendarError(f"school holiday has unknown type {holiday.kind!r}")
        if holiday.start > holiday.end:
            raise CalendarError(f"school holiday ends before it starts: {holiday}")
        if holiday.end < coverage_start or holiday.start > coverage_end:
            raise CalendarError(f"school holiday does not intersect coverage: {holiday}")
    for year in range(coverage_start.year, coverage_end.year + 1):
        year_start = date(year, 1, 1)
        year_end = date(year, 12, 31)
        for code in states:
            if not any(holiday.state == code and holiday.day.year == year for holiday in public_holidays):
                raise CalendarError(f"missing public holidays for {code} in {year}")
            if not any(
                holiday.state == code and holiday.start <= year_end and holiday.end >= year_start
                for holiday in school_holidays
            ):
                raise CalendarError(f"missing school holidays for {code} in {year}")

    return Calendar(
        schema_version=schema_version,
        calendar_version=calendar_version,
        coverage_start=coverage_start,
        coverage_end=coverage_end,
        states=states,
        public_holidays=public_holidays,
        school_holidays=school_holidays,
    )


def load_calendar(path: str | Path | None = None) -> Calendar:
    """Load and validate the packaged calendar, or a path used by tests."""
    calendar_path = _calendar_path() if path is None else Path(path)
    try:
        payload = json.loads(calendar_path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as error:
        raise CalendarError(f"cannot read calendar {calendar_path}: {error}") from error
    if not isinstance(payload, dict):
        raise CalendarError(f"calendar {calendar_path} is not an object")
    return _parse_calendar(payload)


def dataset_version(path: str | Path | None = None) -> str:
    """Return the committed calendar dataset version."""
    return load_calendar(path).calendar_version


def assert_covered(start: date | datetime | str, end: date | datetime | str, calendar: Calendar | None = None) -> None:
    """Fail loudly when a training/scoring range is outside the committed data."""
    data = calendar or load_calendar()
    first = _as_date(start)
    last = _as_date(end)
    if first > last:
        raise CalendarError(f"invalid calendar range {first}..{last}")
    if first < data.coverage_start or last > data.coverage_end:
        raise CalendarCoverageError(
            f"calendar covers {data.coverage_start}..{data.coverage_end}, requested {first}..{last}"
        )


def _primary_school_holiday(day: date, holidays: list[SchoolHoliday]) -> SchoolHoliday | None:
    """Return the longest school break covering a day."""
    covering = [holiday for holiday in holidays if holiday.start <= day <= holiday.end]
    if not covering:
        return None
    # Longest break wins; ties are broken by the earliest start and then the name.
    return min(covering, key=lambda holiday: (-(holiday.end - holiday.start).days, holiday.start, holiday.name))


def _is_bridge_day(day: date, holidays: set[date]) -> bool:
    """Return whether a weekday sits between a public holiday and a weekend."""
    if day.weekday() >= 5 or day in holidays:
        return False
    return (day.weekday() == 4 and day - timedelta(days=1) in holidays) or (
        day.weekday() == 0 and day + timedelta(days=1) in holidays
    )


def daily_rows(
    start: date | datetime | str,
    end: date | datetime | str,
    calendar: Calendar | None = None,
) -> list[tuple[object, ...]]:
    """Expand the ranges into one row per state and date in the requested range."""
    data = calendar or load_calendar()
    first = _as_date(start)
    last = _as_date(end)
    assert_covered(first, last, data)

    public_by_state: dict[str, dict[date, list[PublicHoliday]]] = {code: {} for code in STATE_CODES}
    for holiday in data.public_holidays:
        public_by_state[holiday.state].setdefault(holiday.day, []).append(holiday)
    public_dates = {code: sorted(days) for code, days in public_by_state.items()}
    school_by_state: dict[str, list[SchoolHoliday]] = {code: [] for code in STATE_CODES}
    for holiday in data.school_holidays:
        school_by_state[holiday.state].append(holiday)

    rows: list[tuple[object, ...]] = []
    for code in STATE_CODES:
        dates = public_dates[code]
        holiday_set = set(dates)
        for day in _date_range(first, last):
            holidays = public_by_state[code].get(day, [])
            next_index = bisect_left(dates, day)
            previous_index = bisect_right(dates, day) - 1
            next_days = (dates[next_index] - day).days if next_index < len(dates) else None
            previous_days = (day - dates[previous_index]).days if previous_index >= 0 else None
            primary = _primary_school_holiday(day, school_by_state[code])
            school_day = (day - primary.start).days if primary else None
            until_end = (primary.end - day).days if primary else None
            start_window = any(
                holiday.start - timedelta(days=3) <= day <= holiday.start for holiday in school_by_state[code]
            )
            end_window = any(holiday.end <= day <= holiday.end + timedelta(days=3) for holiday in school_by_state[code])
            rows.append(
                (
                    code,
                    day,
                    bool(holidays),
                    "; ".join(sorted({holiday.name for holiday in holidays})) or None,
                    "; ".join(sorted({holiday.scope for holiday in holidays})) or None,
                    next_days,
                    previous_days,
                    (next_days is not None and next_days <= 3) or (previous_days is not None and previous_days <= 3),
                    primary is not None,
                    primary.name if primary else None,
                    primary.kind if primary else None,
                    school_day,
                    until_end,
                    start_window,
                    end_window,
                    _is_bridge_day(day, holiday_set),
                )
            )
    return rows


def _date_range(start: date, end: date) -> list[date]:
    """Return every date from start through end, inclusive."""
    days = (end - start).days
    return [start + timedelta(days=offset) for offset in range(days + 1)]


def _csv_value(value: object) -> str:
    """Render one daily value for DuckDB CSV ingestion."""
    if value is None:
        return "\\N"
    if value is True:
        return "true"
    if value is False:
        return "false"
    return str(value)


def _copy_daily_rows(connection: duckdb.DuckDBPyConnection, rows: list[tuple[object, ...]]) -> None:
    """Load the daily rows through a temporary CSV, which is much faster than executemany."""
    with tempfile.NamedTemporaryFile("w", suffix=".csv", delete=False, encoding="utf-8", newline="") as handle:
        writer = csv.writer(handle)
        writer.writerows([_csv_value(value) for value in row] for row in rows)
        path = handle.name
    try:
        quoted = path.replace("'", "''")
        connection.execute(f"COPY calendar_daily FROM '{quoted}' (FORMAT csv, HEADER false, NULL '\\N')")
    finally:
        Path(path).unlink(missing_ok=True)


def register_calendar(
    connection: duckdb.DuckDBPyConnection,
    start: date | datetime | str,
    end: date | datetime | str,
    calendar: Calendar | None = None,
) -> None:
    """Create temporary calendar tables for SQL joins."""
    data = calendar or load_calendar()
    rows = daily_rows(start, end, data)
    columns = ", ".join(f"{name} {kind}" for name, kind in zip(DAILY_COLUMNS, _DAILY_TYPES, strict=True))
    connection.execute(f"CREATE OR REPLACE TEMP TABLE calendar_daily ({columns})")
    _copy_daily_rows(connection, rows)
    connection.execute("CREATE OR REPLACE TEMP TABLE calendar_states (name VARCHAR, code VARCHAR)")
    connection.executemany(
        "INSERT INTO calendar_states VALUES (?, ?)",
        [(name, code) for code, name in data.states.items()],
    )


def register_route_states(
    connection: duckdb.DuckDBPyConnection,
    relation: str,
    *,
    origin_state_column: str = "origin_state",
    dest_state_column: str = "dest_state",
) -> None:
    """Validate the route state names and create the name-to-code join table."""
    values = connection.execute(
        f"SELECT DISTINCT {origin_state_column} FROM {relation} "
        f"UNION SELECT DISTINCT {dest_state_column} FROM {relation}"
    ).fetchall()
    rows: list[tuple[str, str]] = []
    for (name,) in values:
        if name is None:
            raise CalendarError(f"route relation {relation!r} has a null state")
        rows.append((str(name), state_code(str(name))))
    connection.execute("CREATE OR REPLACE TEMP TABLE calendar_route_states (name VARCHAR, code VARCHAR)")
    connection.executemany("INSERT INTO calendar_route_states VALUES (?, ?)", sorted(rows))


def route_calendar_sql(
    relation: str,
    *,
    date_column: str = "departure_date",
    origin_state_column: str = "origin_state",
    dest_state_column: str = "dest_state",
) -> str:
    """Return a SELECT that adds the route-level calendar features to ``relation``."""
    return f"""
        SELECT
            r.*,
            (so.code IS NULL) AS origin_state_missing,
            (sd.code IS NULL) AS dest_state_missing,
            (o.date IS NULL OR d.date IS NULL) AS date_missing,
            (so.code IS NULL OR sd.code IS NULL OR o.date IS NULL OR d.date IS NULL) AS calendar_missing,
            COALESCE(o.is_public_holiday, FALSE) AS origin_public_holiday,
            COALESCE(d.is_public_holiday, FALSE) AS dest_public_holiday,
            (COALESCE(o.is_public_holiday, FALSE) OR COALESCE(d.is_public_holiday, FALSE)) AS either_public_holiday,
            o.public_holiday_scope AS origin_public_holiday_scope,
            d.public_holiday_scope AS dest_public_holiday_scope,
            CASE
                WHEN o.days_to_next_public_holiday IS NULL THEN NULL
                ELSE LEAST(o.days_to_next_public_holiday, 14)
            END AS origin_days_to_next_public_holiday,
            CASE
                WHEN d.days_to_next_public_holiday IS NULL THEN NULL
                ELSE LEAST(d.days_to_next_public_holiday, 14)
            END AS dest_days_to_next_public_holiday,
            CASE
                WHEN o.days_to_next_public_holiday IS NULL AND d.days_to_next_public_holiday IS NULL THEN NULL
                ELSE LEAST(
                    COALESCE(o.days_to_next_public_holiday, 14),
                    COALESCE(d.days_to_next_public_holiday, 14),
                    14
                )
            END AS min_days_to_public_holiday,
            COALESCE(o.is_public_holiday_window, FALSE) AS origin_public_holiday_window,
            COALESCE(d.is_public_holiday_window, FALSE) AS dest_public_holiday_window,
            (COALESCE(o.is_public_holiday_window, FALSE) OR COALESCE(d.is_public_holiday_window, FALSE))
                AS either_public_holiday_window,
            COALESCE(o.is_school_holiday, FALSE) AS origin_school_holiday,
            COALESCE(d.is_school_holiday, FALSE) AS dest_school_holiday,
            (COALESCE(o.is_school_holiday, FALSE) OR COALESCE(d.is_school_holiday, FALSE)) AS either_school_holiday,
            (COALESCE(o.is_school_holiday, FALSE) AND COALESCE(d.is_school_holiday, FALSE)) AS both_school_holiday,
            o.school_holiday_type AS origin_school_holiday_type,
            d.school_holiday_type AS dest_school_holiday_type,
            CASE
                WHEN o.school_holiday_day IS NULL THEN NULL
                ELSE LEAST(o.school_holiday_day, 14)
            END AS origin_school_holiday_day,
            CASE
                WHEN d.school_holiday_day IS NULL THEN NULL
                ELSE LEAST(d.school_holiday_day, 14)
            END AS dest_school_holiday_day,
            CASE
                WHEN o.days_until_school_holiday_end IS NULL THEN NULL
                ELSE LEAST(o.days_until_school_holiday_end, 14)
            END AS origin_days_until_school_holiday_end,
            CASE
                WHEN d.days_until_school_holiday_end IS NULL THEN NULL
                ELSE LEAST(d.days_until_school_holiday_end, 14)
            END AS dest_days_until_school_holiday_end,
            (COALESCE(o.is_school_holiday_start_window, FALSE) OR COALESCE(d.is_school_holiday_start_window, FALSE))
                AS either_school_holiday_start_window,
            (COALESCE(o.is_school_holiday_end_window, FALSE) OR COALESCE(d.is_school_holiday_end_window, FALSE))
                AS either_school_holiday_end_window,
            (COALESCE(o.is_bridge_day, FALSE) OR COALESCE(d.is_bridge_day, FALSE)) AS either_bridge_day,
            COALESCE(so.code = sd.code, FALSE) AS is_state_match
        FROM {relation} AS r
        LEFT JOIN calendar_route_states AS so ON so.name = r.{origin_state_column}
        LEFT JOIN calendar_daily AS o ON o.state_code = so.code AND o.date = r.{date_column}
        LEFT JOIN calendar_route_states AS sd ON sd.name = r.{dest_state_column}
        LEFT JOIN calendar_daily AS d ON d.state_code = sd.code AND d.date = r.{date_column}
    """
